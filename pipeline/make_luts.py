def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, p in {**WARM, **ARCHIVE}.items():
        path = write_cube(name, p, TITLES[name], OUT)
        print(f"{path.name}: {path.stat().st_size // 1024} КБ")


if __name__ == "__main__":
    main()
