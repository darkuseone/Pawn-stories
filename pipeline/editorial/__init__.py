"""
editorial — слой РЕДАКТОРСКИХ РЕШЕНИЙ.

Раньше монтаж считался от секундомера: базовая длина кадра плюс замедление
к финалу плюс жребий на переход. Это работает и даёт разные ролики, но
разные ОДИНАКОВЫМ СПОСОБОМ — кривая одна и та же, меняются только числа на
ней. Канал из таких роликов опознаётся как поточный по одному признаку:
у всех загрузок совпадает ФОРМА ритма, даже когда не совпадают цвета.

Здесь ритм считается от СОДЕРЖАНИЯ. Сценарий разбирается на нарративные
доли (крючок, завязка, нагнетание, развязка, выдох, обращение к зрителю),
каждая получает свой темп, и склейки расставляются под смысл, а не под
таймер. Две соседних загрузки различаются не оттенком, а строением.

    beats      сценарий -> доли, у каждой свой редакторский замысел
    pacing     доля -> кривая плотности склеек внутри неё
    variation  вектор стиля ролика, 24 оси, воспроизводимый жребий
    memory     история канала: чем этот ролик обязан отличаться от прошлых
    rails      проверки готового плана на признаки шаблона
    textcard   кинетическая типографика на числах и датах
    edl        выгрузка монтажного листа для доказательства процесса

Порядок сборки:
    beats.analyze()        -> список долей
    variation.draw()       -> вектор стиля, разведённый с историей канала
    pacing.contour()       -> длительности внутри каждой доли
    build.plan_shots()     -> собственно план
    rails.audit()          -> проверка, что не получился шаблон
    edl.export()           -> монтажный лист
"""

